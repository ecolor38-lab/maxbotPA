export class AISummarizer {
  constructor(config) {
    this.config = config;
    this.anthropic = config.anthropic?.apiKey
      ? new Anthropic({ apiKey: config.anthropic.apiKey })
      : null;
    this.openai = config.openai?.apiKey ? new OpenAI({ apiKey: config.openai.apiKey }) : null;
    this.lastPostType = null;
  }

  pickPostType() {
    const optimizedWeights = getOptimizedWeights();
    const types = Object.entries(POST_TYPES).map(([key, type]) => ({
      key,
      ...type,
      weight: optimizedWeights[key] ?? type.weight
    }));

    const available = types.filter((t) => t.key !== this.lastPostType && t.key !== 'sponsored' && t.weight > 0);
    const availableWeight = available.reduce((sum, t) => sum + t.weight, 0);

    let rand = Math.random() * availableWeight;
    for (const type of available) {
      rand -= type.weight;
      if (rand <= 0) {
        this.lastPostType = type.key;
        return type;
      }
    }

    const fallback = available[0];
    this.lastPostType = fallback.key;
    return fallback;
  }

  async generateSummary(articles, forceType = null) {
    const postType = forceType
      ? { key: forceType, ...POST_TYPES[forceType] }
      : this.pickPostType();

    this.lastPostType = postType.key;

    console.log(`🤖 Генерирую пост [${postType.label}] из ${articles.length} статей...`);

    const articlesText = articles
      .map((a, i) => `${i + 1}. ${a.title}\n   ${a.snippet || ''}`)
      .join('\n\n');

    const systemPrompt = postType.system;
    const userPrompt = postType.prompt(articlesText);

    try {
      if (this.anthropic) {
        return await this.callClaude(systemPrompt, userPrompt);
      } else if (this.openai) {
        return await this.callOpenAI(systemPrompt, userPrompt);
      }
    } catch (error) {
      console.log('⚠️ Ошибка API:', error.message);
    }

    return this.getDemoSummary();
  }

  async callClaude(system, prompt) {
    const fullPrompt = prompt + '\n\nВАЖНО: пост ОБЯЗАТЕЛЬНО должен быть длиной 2000-3000 символов. Короткие посты (менее 1500 символов) ЗАПРЕЩЕНЫ. Пиши подробно, развёрнуто, с деталями и примерами.';
    const response = await this.anthropic.messages.create({
      model: this.config.anthropic.model || 'claude-sonnet-4-20250514',
      max_tokens: 4096,
      system: system,
      messages: [{ role: 'user', content: fullPrompt }],
      temperature: 0.8
    });
    return response.content[0].text;
  }

  async callOpenAI(system, prompt) {
    const fullPrompt = prompt + '\n\nВАЖНО: пост ОБЯЗАТЕЛЬНО должен быть длиной 2000-3000 символов. Короткие посты (менее 1500 символов) ЗАПРЕЩЕНЫ. Пиши подробно, развёрнуто, с деталями и примерами.';
    const response = await this.openai.chat.completions.create({
      model: this.config.openai.model || 'gpt-4-turbo-preview',
      messages: [
        { role: 'system', content: system },
        { role: 'user', content: fullPrompt }
      ],
      max_tokens: 4096,
      temperature: 0.8
    });
    return response.choices[0].message.content;
  }

  getDemoSummary() {
    return `🚀 **ИИ-агенты захватывают рабочие процессы**

Notion, Microsoft и Google одновременно запустили автономных ИИ-ассистентов. Они работают 24/7 без участия человека: планируют встречи, пишут отчёты, анализируют данные.

Это больше не «попроси ChatGPT» — это полноценные цифровые сотрудники. Рынок ИИ-агентов вырастет до $65 млрд к 2028 году.

А вы бы доверили ИИ-агенту свою рутину?`;
  }
}
